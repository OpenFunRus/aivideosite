"""MiniMax H3 video-repair preparation and final compositing.

The semantic change is generated by H3. FFmpeg is used only to prepare model
references and to preserve untouched parts of the original MP4.
"""

from __future__ import annotations

import base64
import binascii
import io
import math
import subprocess
from pathlib import Path
from typing import Any

from PIL import Image

from .config import settings


# H3 AddGuide accepts native 17k+5 frame batches. 22 frames is its shortest
# useful motion+audio clip longer than five frames, so each real 0.5-second
# context is gently retimed to 22/24 sec before conditioning.
SPLICE_CONTEXT_SECONDS = 0.5
SPLICE_GUIDE_FRAMES = 22
SPLICE_A_GUIDE_FRAME = 36
SPLICE_B_GUIDE_FRAME = 82
SPLICE_BRIDGE_START_FRAME = SPLICE_A_GUIDE_FRAME + SPLICE_GUIDE_FRAMES
SPLICE_BRIDGE_FRAMES = SPLICE_B_GUIDE_FRAME - SPLICE_BRIDGE_START_FRAME
SPLICE_BRIDGE_SECONDS = SPLICE_BRIDGE_FRAMES / 24


def splice_canvas_size(size: tuple[int, int], quality: str, ratio: str) -> tuple[int, int]:
    """Match the Video tab's presets; 'auto' follows source A's aspect ratio."""
    if quality not in {"480", "720", "1080"}:
        raise ValueError("Качество склейки: 480p, 720p или 1080p.")
    if ratio not in {"auto", "1:1", "16:9", "9:16"}:
        raise ValueError("Неизвестный формат кадра.")
    short = {"480": 480, "720": 736, "1080": 1088}[quality]
    aspect = {"1:1": 1.0, "16:9": 16 / 9, "9:16": 9 / 16}.get(ratio, size[0] / max(1, size[1]))
    if not math.isfinite(aspect) or aspect <= 0:
        raise ValueError("Неверное соотношение сторон исходного видео.")
    grid_up = lambda value: max(32, int(math.ceil(value / 32)) * 32)
    return (grid_up(short * max(1.0, aspect)), grid_up(short * max(1.0, 1 / aspect)))


def _has_audio(path: Path) -> bool:
    result = subprocess.run(
        [str(settings.ffprobe_bin), "-v", "error", "-select_streams", "a:0",
         "-show_entries", "stream=index", "-of", "csv=p=0", str(path)],
        capture_output=True, text=True, timeout=30, check=False,
    )
    return result.returncode == 0 and bool(result.stdout.strip())


def h3_duration(selected_seconds: float) -> int:
    if selected_seconds <= 0 or selected_seconds > 15:
        raise ValueError("Выберите от 1 до 15 секунд для исправления H3.")
    return 5 if selected_seconds <= 5 else 10 if selected_seconds <= 10 else 15


def ai_canvas_size(width: int, height: int) -> tuple[int, int]:
    scale = min(1.0, 768 / max(width, height))
    return (max(256, int(round(width * scale / 32)) * 32),
            max(256, int(round(height * scale / 32)) * 32))


def _run(command: list[str]) -> None:
    result = subprocess.run(command, capture_output=True, text=True, timeout=600, check=False)
    if result.returncode != 0:
        raise RuntimeError("FFmpeg: " + result.stderr[-1200:])


def _tempo_filters(speed: float) -> str:
    """Audio tempo expression for arbitrary positive speed (atempo: 0.5..2)."""
    if not math.isfinite(speed) or speed <= 0:
        raise ValueError("Invalid audio speed")
    factors = []
    while speed > 2:
        factors.append(2.0)
        speed /= 2
    while speed < 0.5:
        factors.append(0.5)
        speed /= 0.5
    factors.append(speed)
    return ",".join(f"atempo={factor:.6f}" for factor in factors)


def decode_mask(data_url: str, destination: Path) -> None:
    if not data_url.startswith("data:image/png;base64,") or len(data_url) > 2_800_000:
        raise ValueError("Передайте PNG-маску размером не более 2 МБ.")
    try:
        raw = base64.b64decode(data_url.split(",", 1)[1], validate=True)
        with Image.open(io.BytesIO(raw)) as image:
            mask = image.convert("L")
            if mask.width < 16 or mask.height < 16 or mask.width > 2048 or mask.height > 2048:
                raise ValueError("Недопустимый размер маски.")
            if mask.getextrema()[1] < 128:
                raise ValueError("Маска пустая. Закрасьте область объекта белым цветом.")
            mask.save(destination, format="PNG")
    except (ValueError, binascii.Error, OSError) as exc:
        raise ValueError("Не удалось прочитать PNG-маску: " + str(exc)) from exc


def prepare_ai_inputs(
    *, job_id: str, mode: str, first_video: Path, first_duration: float,
    start: float, end: float, size: tuple[int, int],
    second_video: Path | None = None, mask_png: str = "",
    splice_size: tuple[int, int] | None = None,
) -> dict[str, Any]:
    """Stage H3-compatible video references and still-frame guides.

    For a splice, H3 receives two native 22-frame guided motion clips,
    derived from 0.5 seconds of each input; only the unanchored 24 frames
    between them are taken from the H3 output.
    """
    width, height = splice_size if mode == "splice" and splice_size else ai_canvas_size(*size)
    segment_duration = 1.0 if mode == "splice" else end - start
    seconds = h3_duration(segment_duration)
    created: list[Path] = []

    def path(label: str, ext: str) -> Path:
        file = settings.upload_dir / f"{job_id}_{label}.{ext}"
        created.append(file)
        return file

    def frame(source: Path, moment: float, label: str) -> Path:
        destination = path(label, "png")
        for seek in (moment, moment - .15, moment - .5):
            _run([str(settings.ffmpeg_bin), "-y", "-ss", f"{max(0, seek):.6f}",
                  "-i", str(source), "-frames:v", "1", "-vf", f"scale={width}:{height}", str(destination)])
            if destination.is_file():
                break
        if not destination.is_file():
            raise ValueError("Не удалось извлечь опорный кадр из исходного видео.")
        return destination

    def clip(source: Path, moment: float, length: float, target: float, label: str) -> Path:
        destination = path(label, "mp4")
        rate = target / length
        _run([str(settings.ffmpeg_bin), "-y", "-ss", f"{max(0, moment):.6f}",
              "-t", f"{length:.6f}", "-i", str(source),
              "-map", "0:v:0", "-map", "0:a:0?",
              "-vf", f"setpts=(PTS-STARTPTS)*{rate:.8f},fps=24,tpad=stop_mode=clone:stop_duration=0.5,trim=end_frame={round(target * 24)},scale={width}:{height}:force_original_aspect_ratio=decrease,pad={width}:{height}:(ow-iw)/2:(oh-ih)/2,format=yuv420p",
              "-af", _tempo_filters(length / target),
              "-c:v", "libx264", "-preset", "fast", "-crf", "21",
              "-c:a", "aac", "-b:a", "128k", "-t", f"{target:.6f}", str(destination)])
        return destination

    try:
        if mode == "splice":
            if second_video is None:
                raise ValueError("Для перехода выберите два видео.")
            guide_seconds = SPLICE_GUIDE_FRAMES / 24
            before = clip(first_video, max(0, first_duration - SPLICE_CONTEXT_SECONDS),
                          SPLICE_CONTEXT_SECONDS, guide_seconds, "transition_context_a")
            after = clip(second_video, 0, SPLICE_CONTEXT_SECONDS, guide_seconds, "transition_context_b")
            guides = [
                {"type": "video", "path": str(before), "temporary": True,
                 "frame_idx": SPLICE_A_GUIDE_FRAME, "with_audio": _has_audio(before),
                 "source_name": "Final 0.5 seconds of video A"},
                {"type": "video", "path": str(after), "temporary": True,
                 "frame_idx": SPLICE_B_GUIDE_FRAME, "with_audio": _has_audio(after),
                 "source_name": "First 0.5 seconds of video B"},
            ]
            references = []
            control = {"mode": "none"}
        else:
            reference = clip(first_video, start, segment_duration, seconds, "source_segment")
            first_frame = frame(first_video, start, "segment_first")
            last_frame = frame(first_video, end - 1 / 24, "segment_last")
            references = [{"type": "video", "path": str(reference), "temporary": True, "source_name": "Original scene"}]
            guides = [
                {"path": str(first_frame), "temporary": True, "frame_idx": 0, "source_name": "Unchanged boundary at start"},
                {"path": str(last_frame), "temporary": True, "frame_idx": -1, "source_name": "Unchanged boundary at end"},
            ]
            control = {"mode": "none"}
            if mode == "motion":
                control = {"mode": "canny_auto", "control_video_path": str(reference), "strength": 1.0}
            elif mode == "object":
                mask_file = path("object_mask", "png")
                decode_mask(mask_png, mask_file)
                mask_video = path("object_mask", "mp4")
                _run([str(settings.ffmpeg_bin), "-y", "-loop", "1", "-framerate", "24", "-i", str(mask_file),
                      "-t", str(seconds), "-vf", f"scale={width}:{height}:flags=neighbor,format=yuv420p",
                      "-c:v", "libx264", "-preset", "fast", "-crf", "0", str(mask_video)])
                mask_file.unlink(missing_ok=True)
                created.remove(mask_file)
                control = {"mode": "inpaint", "source_video_path": str(reference),
                           "mask_video_path": str(mask_video), "strength": 1.0}
        return {"width": width, "height": height, "seconds": seconds,
                "references": references, "guides": guides, "control": control}
    except Exception:
        for temporary in created:
            temporary.unlink(missing_ok=True)
        raise


def assembly_command(
    *, mode: str, source: Path, generated: Path, destination: Path,
    start: float, end: float, source_duration: float, size: tuple[int, int],
    generated_duration: float, source_has_audio: bool, generated_has_audio: bool,
    second: Path | None = None, second_duration: float = 0, second_has_audio: bool = False,
) -> list[str]:
    """Build an FFmpeg montage: original outside interval, H3 inside interval."""
    width, height = size
    width -= width % 2
    height -= height % 2
    if generated_duration <= 0:
        raise ValueError("MiniMax H3 did not produce a valid video.")
    filters: list[str] = []
    sources: list[tuple[Path, float, float, bool, bool]] = []
    if mode == "splice":
        if second is None:
            raise ValueError("Second clip missing")
        sources = [(source, 0, source_duration, source_has_audio, False),
                   (generated, SPLICE_BRIDGE_START_FRAME / 24, SPLICE_BRIDGE_SECONDS, generated_has_audio, True),
                   (second, 0, second_duration, second_has_audio, False)]
    elif mode == "sound":
        sources = [(source, 0, start, source_has_audio, False),
                   (generated, 0, end - start, generated_has_audio, True),
                   (source, end, source_duration - end, source_has_audio, False)]
    else:
        sources = [(source, 0, start, source_has_audio, False),
                   (generated, 0, end - start, generated_has_audio, True),
                   (source, end, source_duration - end, source_has_audio, False)]
    sources = [spec for spec in sources if spec[2] > .02]
    # Sound-only replacements must always preserve the entire *original* video,
    # even when the selection starts at zero and the prefix is omitted.
    command = [str(settings.ffmpeg_bin), "-y"]
    audio_input_offset = 0
    if mode == "sound":
        command.extend(["-i", str(source)])
        audio_input_offset = 1
    for path, *_ in sources:
        command.extend(["-i", str(path)])
    audio_outputs = []
    video_outputs = []
    for i, (path, offset, length, has_audio, is_generated) in enumerate(sources):
        input_idx = i + audio_input_offset
        if mode != "sound":
            stretch = (length / (1 if mode == "splice" else generated_duration)) if is_generated else 1.0
            filters.append(
                f"[{input_idx}:v:0]trim=start={offset:.6f}:duration={(1 if mode == 'splice' and is_generated else generated_duration if is_generated else length):.6f},"
                f"setpts=(PTS-STARTPTS)*{stretch:.8f},"
                f"scale={width}:{height}:force_original_aspect_ratio=decrease,"
                f"pad={width}:{height}:(ow-iw)/2:(oh-ih)/2,setsar=1,fps=24,settb=AVTB,format=yuv420p[v{i}]"
            )
            video_outputs.append(f"[v{i}]")
        if has_audio:
            original_length = 1 if mode == "splice" and is_generated else generated_duration if is_generated else length
            tempo = "," + _tempo_filters(original_length / length) if is_generated and abs(original_length - length) > .01 else ""
            filters.append(
                f"[{input_idx}:a:0]atrim=start={offset:.6f}:duration={original_length:.6f},"
                "asetpts=PTS-STARTPTS,aresample=48000," + (tempo[1:] + "," if tempo else "") +
                "aformat=sample_fmts=fltp:channel_layouts=stereo,"
                f"apad,atrim=duration={length:.6f}[a{i}]"
            )
        else:
            filters.append(f"anullsrc=r=48000:cl=stereo,atrim=duration={length:.6f},asetpts=PTS-STARTPTS[a{i}]")
        audio_outputs.append(f"[a{i}]")
    if mode == "sound":
        filters.append("".join(audio_outputs) + f"concat=n={len(sources)}:v=0:a=1[aout]")
        command.extend(["-filter_complex", ";".join(filters), "-map", "0:v:0", "-map", "[aout]", "-c:v", "copy"])
    else:
        filters.append("".join(v + a for v, a in zip(video_outputs, audio_outputs)) +
                       f"concat=n={len(sources)}:v=1:a=1[vout][aout]")
        command.extend(["-filter_complex", ";".join(filters), "-map", "[vout]", "-map", "[aout]",
                        "-c:v", "libx264", "-preset", "medium", "-crf", "18", "-pix_fmt", "yuv420p", "-r", "24"])
    command.extend(["-c:a", "aac", "-b:a", "192k", "-movflags", "+faststart", str(destination)])
    return command
